<?php

namespace App\Services\Application\Menu;

use App\Models\Application\AppMenu;
use App\Models\Application\AppMenuItem;
use App\Services\AutoInstallationService;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

/**
 * Class AppMenusSyncService.
 * Moves the menus built with the menu builder (app_menu, app_menu_item) between environments.
 *
 * export() reads the menus from the local database (see `php artisan app-menus:export`),
 * import() writes them into the current database (the "app_menus_sync" auto-installation type).
 *
 * Import rules:
 *  - only the company-less menus (company_id NULL) are synced, matched by their key,
 *  - a menu in the file gets exactly the items of the file (its items are rebuilt),
 *  - `active` of a menu is only set when it is created, so switching a menu off on the server is kept,
 *  - menus that are not in the file are never deleted.
 */
class AppMenusSyncService
{
    /**Installation type handled by AutoInstallationService */
    const INSTALLATION_TYPE = 'app_menus_sync';

    /**File the export writes and the auto-installation reads */
    const FILE_NAME = 'app_menus_sync.json';

    private const ITEM_FIELDS = ['type', 'title', 'icon', 'route_name', 'url', 'new_tab', 'permission', 'active'];

    public static function filePath(): string
    {
        return app(AutoInstallationService::class)->getInstallationPath() . DIRECTORY_SEPARATOR . self::FILE_NAME;
    }

    /**
     * @return array ['menus' => count, 'items' => count]
     */
    public static function exportToFile(): array
    {
        $data = self::export();

        $content = [
            'type'        => self::INSTALLATION_TYPE,
            'description' => 'Menus of the menu builder, generated by `php artisan app-menus:export`. Do not edit by hand.',
            'data'        => $data,
        ];

        File::ensureDirectoryExists(dirname(self::filePath()));
        File::put(self::filePath(), json_encode($content, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");

        $count = 0;
        array_walk_recursive($data, function ($value, $key) use (&$count) {
            if ($key === 'type') $count++;
        });

        return ['menus' => count($data['menus']), 'items' => $count];
    }

    /**
     * @return array counts of created / updated menus and items
     * @throws \Throwable
     */
    public static function importFromFile(): array
    {
        return app(AutoInstallationService::class)->installFile(self::FILE_NAME);
    }

    public static function export(): array
    {
        $menus = AppMenu::whereNull('company_id')->orderBy('key')->get();

        return [
            'menus' => $menus->map(function (AppMenu $menu) {
                $items = AppMenuItem::where('menu_id', $menu->id)->orderBy('position')->orderBy('id')->get()->groupBy(fn ($i) => $i->parent_id ?? 0);
                $build = function (int $parentId) use (&$build, $items) {
                    return ($items[$parentId] ?? collect())->map(function (AppMenuItem $item) use (&$build) {
                        $row = [];
                        foreach (self::ITEM_FIELDS as $field) $row[$field] = $item->{$field};
                        if ($item->isGroup()) $row['children'] = $build($item->id);
                        return $row;
                    })->values()->all();
                };

                return [
                    'key'    => $menu->key,
                    'name'   => $menu->name,
                    'active' => (bool) $menu->active,
                    'items'  => $build(0),
                ];
            })->values()->all(),
        ];
    }

    /**
     * @param array $data the "data" of the installation file
     * @return array
     * @throws \Exception
     */
    public static function import(array $data): array
    {
        if (!isset($data['menus']) || !is_array($data['menus'])) {
            throw new \Exception('app_menus_sync must contain a "menus" list');
        }

        $stats = ['menus_created' => 0, 'menus_updated' => 0, 'items' => 0];

        DB::transaction(function () use ($data, &$stats) {
            foreach ($data['menus'] as $menuData) {
                if (empty($menuData['key']) || empty($menuData['name'])) {
                    throw new \Exception('Every menu needs a "key" and a "name": ' . json_encode($menuData));
                }

                $menu = AppMenu::whereNull('company_id')->where('key', $menuData['key'])->first();
                if ($menu) {
                    $menu->update(['name' => $menuData['name']]);
                    AppMenuItem::where('menu_id', $menu->id)->whereNull('parent_id')->delete(); // children cascade
                    $stats['menus_updated']++;
                } else {
                    $menu = AppMenu::create(['key' => $menuData['key'], 'name' => $menuData['name'], 'company_id' => NULL, 'active' => (bool) ($menuData['active'] ?? TRUE)]);
                    $stats['menus_created']++;
                }

                self::importItems($menu, $menuData['items'] ?? [], NULL, 1, $stats);
            }
        });

        MenuRenderer::flush();
        return $stats;
    }

    private static function importItems(AppMenu $menu, array $items, ?int $parentId, int $depth, array &$stats): void
    {
        if ($items && $depth > MenuBuilderService::MAX_DEPTH) throw new \Exception("Menu \"{$menu->key}\" is deeper than " . MenuBuilderService::MAX_DEPTH . ' levels');

        foreach (array_values($items) as $position => $itemData) {
            if (!array_key_exists($itemData['type'] ?? '', AppMenuItem::TYPES)) {
                throw new \Exception("Menu \"{$menu->key}\": unknown item type " . json_encode($itemData['type'] ?? NULL));
            }

            $values = [];
            foreach (self::ITEM_FIELDS as $field) $values[$field] = $itemData[$field] ?? NULL;
            $item = AppMenuItem::create($values + [
                'menu_id'   => $menu->id,
                'parent_id' => $parentId,
                'position'  => $position,
                'new_tab'   => (bool) ($itemData['new_tab'] ?? FALSE),
                'active'    => (bool) ($itemData['active'] ?? TRUE),
            ]);
            $stats['items']++;

            if ($item->isGroup()) self::importItems($menu, $itemData['children'] ?? [], $item->id, $depth + 1, $stats);
        }
    }
}
