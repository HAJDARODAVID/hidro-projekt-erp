<?php

namespace App\Services\Application;

use App\Services\AutoInstallationService;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

/**
 * Class AppTranslationsSyncService.
 * Moves the app translations (app_translations, used by translator()) between environments.
 *
 * Workflow (local):
 *  1. php artisan translations:scan      the untranslated translator() strings -> database/translations/{lang}.json
 *  2. fill in the translations in that file
 *  3. php artisan translations:import    the file -> local app_translations
 *  4. php artisan translations:export    local app_translations -> the sync file (auto-installation)
 *  5. commit, the next deploy installs it (the "app_translations_sync" auto-installation type)
 *
 * Import rules:
 *  - a row is matched by its exact value + lang, its translation is created or overwritten,
 *  - empty translations are skipped,
 *  - translations that are not in the file are never deleted.
 */
class AppTranslationsSyncService
{
    /**Installation type handled by AutoInstallationService */
    const INSTALLATION_TYPE = 'app_translations_sync';

    /**File the export writes and the auto-installation reads */
    const FILE_NAME = 'app_translations_sync.json';

    /**Length of app_translations.value / .translation */
    const MAX_LENGTH = 255;

    public static function filePath(): string
    {
        return app(AutoInstallationService::class)->getInstallationPath() . DIRECTORY_SEPARATOR . self::FILE_NAME;
    }

    /** The file translations:scan writes and translations:import reads */
    public static function workFilePath(string $lang): string
    {
        return base_path('database/translations/' . $lang . '.json');
    }

    /**
     * @return array ['languages' => count, 'translations' => count]
     */
    public static function exportToFile(): array
    {
        $data = self::export();

        $content = [
            'type'        => self::INSTALLATION_TYPE,
            'description' => 'App translations, generated by `php artisan translations:export`. Do not edit by hand, edit database/translations/{lang}.json and run translations:import.',
            'data'        => $data,
        ];

        File::ensureDirectoryExists(dirname(self::filePath()));
        File::put(self::filePath(), json_encode($content, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");

        return [
            'languages'    => count($data['translations']),
            'translations' => array_sum(array_map('count', $data['translations'])),
        ];
    }

    /**
     * @return array counts of created / updated / unchanged translations
     * @throws \Throwable
     */
    public static function importFromFile(): array
    {
        return app(AutoInstallationService::class)->installFile(self::FILE_NAME);
    }

    /**
     * Import the work file of a language (database/translations/{lang}.json: { "value": "translation" }).
     *
     * @throws \Exception
     */
    public static function importWorkFile(string $lang): array
    {
        $path = self::workFilePath($lang);
        if (!File::exists($path)) throw new \Exception("The file does not exist: $path (run translations:scan first)");

        $translations = json_decode(File::get($path), TRUE);
        if (!is_array($translations)) throw new \Exception("The file is not valid JSON: $path");

        return self::import(['translations' => [$lang => $translations]]);
    }

    public static function export(): array
    {
        $translations = [];
        $rows = DB::table('app_translations')->orderBy('lang')->orderBy('value')->get(['value', 'lang', 'translation']);
        foreach ($rows as $row) {
            $translations[$row->lang][$row->value] = $row->translation;
        }
        return ['translations' => $translations];
    }

    /**
     * @param array $data the "data" of the installation file: ['translations' => [lang => [value => translation]]]
     * @return array ['created' => int, 'updated' => int, 'unchanged' => int, 'skipped_empty' => int]
     * @throws \Exception
     */
    public static function import(array $data): array
    {
        if (!isset($data['translations']) || !is_array($data['translations'])) {
            throw new \Exception('app_translations_sync must contain a "translations" object: { "lang": { "value": "translation" } }');
        }

        $stats = ['created' => 0, 'updated' => 0, 'unchanged' => 0, 'skipped_empty' => 0];

        DB::transaction(function () use ($data, &$stats) {
            foreach ($data['translations'] as $lang => $translations) {
                if (!is_string($lang) || !preg_match('/^[a-z]{2,5}$/', $lang)) throw new \Exception('Invalid language code: ' . json_encode($lang));
                if (!is_array($translations)) throw new \Exception("The translations of \"$lang\" must be an object");

                // Exact (case sensitive) map of what is in the database now
                $existing = [];
                foreach (DB::table('app_translations')->where('lang', $lang)->get(['value', 'translation']) as $row) {
                    $existing[$row->value] = $row->translation;
                }

                $rows = [];
                foreach ($translations as $value => $translation) {
                    // Not trimmed: fragments like "Payroll info for: " are joined in the code, their spaces matter
                    $value = (string) $value;
                    $translation = (string) $translation;
                    if (trim($value) === '' || trim($translation) === '') {
                        $stats['skipped_empty']++;
                        continue;
                    }
                    if (mb_strlen($value) > self::MAX_LENGTH || mb_strlen($translation) > self::MAX_LENGTH) {
                        throw new \Exception("Longer than " . self::MAX_LENGTH . " characters ($lang): " . mb_substr($value, 0, 80));
                    }

                    if (!array_key_exists($value, $existing)) {
                        $stats['created']++;
                    } elseif ($existing[$value] !== $translation) {
                        $stats['updated']++;
                    } else {
                        $stats['unchanged']++;
                        continue;
                    }
                    $rows[] = ['value' => $value, 'lang' => $lang, 'translation' => $translation];
                }

                foreach (array_chunk($rows, 200) as $chunk) {
                    DB::table('app_translations')->upsert($chunk, ['value', 'lang'], ['translation']);
                }
            }
        });

        return $stats;
    }
}
