<?php

namespace App\Services\Application\Acl;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;
use App\Services\AutoInstallationService;
use App\Models\Application\AppModule;
use App\Models\Application\AppModuleRoute;
use App\Models\Application\Acl\AclRole;
use App\Models\Application\Acl\AclPermission;

/**
 * Class AclSyncService.
 * Moves the ACL definitions (permissions, roles and the permissions of each role) between
 * environments in a file of its own. Built like AppModulesSyncService, but separate from it.
 *
 * export() reads them from the local database (see `php artisan acl:export`),
 * import() writes them into the current database (the "acl_sync" auto-installation type).
 *
 * What is synced:   acl_permissions, acl_roles, acl_role_permission
 * What is NOT:      acl_user_role, acl_user_permission. Users differ between databases,
 *                   who gets which role is decided on each server.
 *
 * Import rules:
 *  - permissions and roles are matched by ID, then by `key`. A row matched by key gets the
 *    ID from the file (re-keyed), so the next sync matches it by ID.
 *  - name, description, module and guarded route are taken from the file.
 *  - a role's `active` is only set when the role is created, so switching a role on or off
 *    on the server is not undone by the next sync.
 *  - role permissions are only ADDED: a permission the file gives a role is granted, but
 *    permissions given on the server are kept. Removing one has to be done on each server.
 *  - rows that are not in the file are never deleted.
 *  - module and route are matched by ID, then by their natural key (module: `module`,
 *    route: module + `route_name`). If they don't exist on this server the permission is
 *    saved without them and a warning is returned.
 *
 * The file name sorts after app_modules_sync.json, so on a deploy the modules and routes
 * are installed first and the routes the permissions guard already exist.
 */
class AclSyncService
{
    /**Installation type handled by AutoInstallationService */
    const INSTALLATION_TYPE = 'acl_sync';

    /**File the export writes and the auto-installation reads (must sort after app_modules_sync.json) */
    const FILE_NAME = 'app_sync_acl.json';

    /**
     * Path of the sync file in the auto-installations folder.
     *
     * @return string
     */
    public static function filePath(): string
    {
        return app(AutoInstallationService::class)->getInstallationPath() . DIRECTORY_SEPARATOR . self::FILE_NAME;
    }

    /**
     * Export the ACL definitions into the sync file (see filePath()).
     *
     * @return array ['permissions' => count, 'roles' => count, 'role_permissions' => count, 'warnings' => [...]]
     */
    public static function exportToFile(): array
    {
        $warnings = [];
        $data = self::export($warnings);

        $content = [
            'type'        => self::INSTALLATION_TYPE,
            'description' => 'ACL permissions and roles, generated by `php artisan acl:export`. Do not edit by hand.',
            'data'        => $data,
        ];

        File::ensureDirectoryExists(dirname(self::filePath()));
        File::put(self::filePath(), json_encode($content, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");

        return [
            'permissions'      => count($data['permissions']),
            'roles'            => count($data['roles']),
            'role_permissions' => array_sum(array_map(fn ($role) => count($role['permissions']), $data['roles'])),
            'warnings'         => $warnings,
        ];
    }

    /**
     * Import the sync file now, through the auto-installer so the run is recorded
     * (the next deploy then skips the file if its data didn't change).
     *
     * @return array counts of created / updated / re-keyed rows and the warnings
     * @throws \Throwable
     */
    public static function importFromFile(): array
    {
        return app(AutoInstallationService::class)->installFile(self::FILE_NAME);
    }

    /**
     * Rebuild the ACL from the sync file: afterwards the permissions, roles and role permissions
     * are exactly what the file holds.
     *  - permissions and roles that are not in the file are DELETED (with their role permissions,
     *    user roles and user overrides),
     *  - each role gets exactly the permissions the file gives it,
     *  - a role's `active` is taken from the file too.
     * User roles and user overrides of the permissions and roles that stay are kept.
     * Runs directly, not through the auto-installer (it's a manual reset, not a deploy step).
     *
     * @return array counts of created / updated / re-keyed / deleted rows and the warnings
     * @throws \Throwable
     */
    public static function rebuildFromFile(): array
    {
        if (!File::exists(self::filePath())) throw new \Exception('The ACL sync file does not exist: ' . self::FILE_NAME);

        $content = json_decode(File::get(self::filePath()), TRUE);
        if (!is_array($content) || ($content['type'] ?? NULL) !== self::INSTALLATION_TYPE || !isset($content['data'])) {
            throw new \Exception('The ACL sync file is not valid (expected type "' . self::INSTALLATION_TYPE . '" with "data").');
        }
        /**An empty file would delete the whole ACL, that is never what a rebuild is meant for */
        if (empty($content['data']['permissions']) && empty($content['data']['roles'])) {
            throw new \Exception('The ACL sync file holds no permissions and no roles, the ACL was not rebuilt.');
        }

        return self::import($content['data'], TRUE);
    }

    /**
     * All permissions and roles, sorted so the file only changes when the data changes.
     * Modules and routes are written with their natural key too, in case their ID differs on the server.
     *
     * @param array $warnings filled with the problems found while exporting
     * @return array
     */
    public static function export(array &$warnings = []): array
    {
        $modules = AppModule::pluck('module', 'id');
        $routes = AppModuleRoute::get(['id', 'route_name', 'module_id'])->keyBy('id');

        $permissions = AclPermission::orderBy('key')->get()->map(function (AclPermission $permission) use ($modules, $routes, &$warnings) {
            $module = NULL;
            if ($permission->module_id) {
                if (isset($modules[$permission->module_id])) {
                    $module = ['id' => $permission->module_id, 'module' => $modules[$permission->module_id]];
                } else {
                    $warnings[] = "Permission \"{$permission->key}\": module {$permission->module_id} doesn't exist, exported without a module.";
                }
            }

            $route = NULL;
            if ($permission->route_id) {
                $routeModel = $routes[$permission->route_id] ?? NULL;
                if ($routeModel) {
                    $route = ['id' => $routeModel->id, 'route_name' => $routeModel->route_name, 'module' => $modules[$routeModel->module_id] ?? NULL];
                } else {
                    $warnings[] = "Permission \"{$permission->key}\": route {$permission->route_id} doesn't exist, exported without a route.";
                }
            }

            return [
                'id'          => $permission->id,
                'key'         => $permission->key,
                'name'        => $permission->name,
                'description' => $permission->description,
                'module'      => $module,
                'route'       => $route,
            ];
        })->values()->all();

        $roles = AclRole::with(['permissions' => fn ($q) => $q->orderBy('key')])->orderBy('key')->get()->map(fn (AclRole $role) => [
            'id'          => $role->id,
            'key'         => $role->key,
            'name'        => $role->name,
            'description' => $role->description,
            'active'      => (bool) $role->active,
            'permissions' => $role->permissions->pluck('key')->values()->all(),
        ])->values()->all();

        return ['permissions' => $permissions, 'roles' => $roles];
    }

    /**
     * Create / update the permissions and roles from the exported data, in one transaction.
     *
     * @param array $data the "data" of the installation file
     * @param bool $exact TRUE = rebuild: also delete what isn't in the file, set role permissions
     *                    and `active` exactly as in the file (see rebuildFromFile()).
     *                    FALSE = the deploy sync: create / update / add only.
     * @return array counts of created / updated / re-keyed / deleted rows and the warnings
     * @throws \Exception
     */
    public static function import(array $data, bool $exact = FALSE): array
    {
        if (!isset($data['permissions']) || !is_array($data['permissions']) || !isset($data['roles']) || !is_array($data['roles'])) {
            throw new \Exception('acl_sync must contain a "permissions" and a "roles" list');
        }

        $stats = [
            'permissions_created' => 0, 'permissions_updated' => 0,
            'roles_created' => 0, 'roles_updated' => 0,
            'role_permissions_added' => 0, 'rekeyed' => 0,
            'warnings' => [],
        ];
        if ($exact) $stats += ['permissions_deleted' => 0, 'roles_deleted' => 0, 'role_permissions_removed' => 0];

        DB::transaction(function () use ($data, $exact, &$stats) {
            /**Permission key => ID on this server, for the role permissions */
            $permissionIDs = [];
            foreach ($data['permissions'] as $permissionData) {
                $permission = self::importPermission($permissionData, $stats);
                $permissionIDs[$permission->key] = $permission->id;
            }

            $roleIDs = [];
            foreach ($data['roles'] as $roleData) {
                $role = self::importRole($roleData, $stats, $exact);
                $roleIDs[] = $role->id;

                $filePermissionIDs = [];
                foreach ($roleData['permissions'] ?? [] as $permissionKey) {
                    $permissionID = $permissionIDs[$permissionKey] ?? ($exact ? NULL : AclPermission::where('key', $permissionKey)->value('id'));
                    if ($permissionID === NULL) {
                        $stats['warnings'][] = "Role \"{$role->key}\": permission \"{$permissionKey}\" doesn't exist, skipped.";
                        continue;
                    }
                    $filePermissionIDs[] = $permissionID;
                    $stats['role_permissions_added'] += DB::table('acl_role_permission')->insertOrIgnore(['role_id' => $role->id, 'permission_id' => $permissionID]);
                }

                /**Rebuild: the role holds exactly the permissions of the file */
                if ($exact) {
                    $stats['role_permissions_removed'] += DB::table('acl_role_permission')
                        ->where('role_id', $role->id)
                        ->whereNotIn('permission_id', $filePermissionIDs ?: [''])
                        ->delete();
                }
            }

            /**Rebuild: delete what isn't in the file (role permissions, user roles and overrides go with them, see the FKs) */
            if ($exact) {
                $stats['permissions_deleted'] = AclPermission::whereNotIn('id', array_values($permissionIDs) ?: [''])->delete();
                $stats['roles_deleted'] = AclRole::whereNotIn('id', $roleIDs ?: [''])->delete();
            }
        });

        AclService::flush();
        return $stats;
    }

    /**
     * @param array $data
     * @param array $stats
     * @return AclPermission
     * @throws \Exception
     */
    private static function importPermission(array $data, array &$stats): AclPermission
    {
        if (empty($data['id']) || empty($data['key'])) {
            throw new \Exception('Every permission needs an "id" and a "key": ' . json_encode($data));
        }

        $permission = AclPermission::find($data['id']) ?? AclPermission::where('key', $data['key'])->first();

        // Same permission created separately on this server: take over the ID from the file
        if ($permission && $permission->id !== $data['id']) {
            self::rekey('acl_permissions', 'permission_id', $permission->id, $data['id'], ['acl_role_permission', 'acl_user_permission']);
            $permission = AclPermission::find($data['id']);
            $stats['rekeyed']++;
        }

        $routeID = self::resolveRouteID($data['route'] ?? NULL, $data['key'], $stats);
        $values = [
            'key'         => $data['key'],
            'name'        => $data['name'] ?? $data['key'],
            'description' => $data['description'] ?? NULL,
            'module_id'   => self::resolveModuleID($data['module'] ?? NULL, $data['key'], $stats),
            'route_id'    => $routeID,
        ];

        // A route can be guarded by one permission only: the file wins over a binding made on the server
        if ($routeID !== NULL) {
            $other = AclPermission::where('route_id', $routeID)->where('id', '!=', $data['id'])->first();
            if ($other) {
                $other->update(['route_id' => NULL]);
                $stats['warnings'][] = "Route of \"{$data['key']}\" was guarded by \"{$other->key}\" on this server, that binding was removed.";
            }
        }

        if ($permission) {
            $permission->update($values);
            $stats['permissions_updated']++;
            return $permission;
        }

        $permission = new AclPermission($values);
        $permission->id = $data['id'];
        $permission->save();
        $stats['permissions_created']++;
        return $permission;
    }

    /**
     * @param array $data
     * @param array $stats
     * @param bool $exact rebuild: also take `active` from the file for existing roles
     * @return AclRole
     * @throws \Exception
     */
    private static function importRole(array $data, array &$stats, bool $exact = FALSE): AclRole
    {
        if (empty($data['id']) || empty($data['key'])) {
            throw new \Exception('Every role needs an "id" and a "key": ' . json_encode($data));
        }

        $role = AclRole::find($data['id']) ?? AclRole::where('key', $data['key'])->first();

        // Same role created separately on this server: take over the ID from the file
        if ($role && $role->id !== $data['id']) {
            self::rekey('acl_roles', 'role_id', $role->id, $data['id'], ['acl_role_permission', 'acl_user_role']);
            $role = AclRole::find($data['id']);
            $stats['rekeyed']++;
        }

        $values = [
            'key'         => $data['key'],
            'name'        => $data['name'] ?? $data['key'],
            'description' => $data['description'] ?? NULL,
        ];

        if ($role) {
            if ($exact) $values['active'] = (bool) ($data['active'] ?? TRUE);
            $role->update($values);
            $stats['roles_updated']++;
            return $role;
        }

        $role = new AclRole($values + ['active' => (bool) ($data['active'] ?? TRUE)]);
        $role->id = $data['id'];
        $role->save();
        $stats['roles_created']++;
        return $role;
    }

    /**
     * Change the ID of a row and of every row pointing at it. The foreign keys have no
     * ON UPDATE CASCADE, so they are switched off for the change (inside the transaction).
     *
     * @param string $table
     * @param string $column column holding the ID in the child tables
     * @param string $oldID
     * @param string $newID
     * @param array $childTables
     * @return void
     */
    private static function rekey(string $table, string $column, string $oldID, string $newID, array $childTables): void
    {
        Schema::disableForeignKeyConstraints();
        try {
            DB::table($table)->where('id', $oldID)->update(['id' => $newID]);
            foreach ($childTables as $childTable) {
                DB::table($childTable)->where($column, $oldID)->update([$column => $newID]);
            }
        } finally {
            Schema::enableForeignKeyConstraints();
        }
    }

    /**
     * The ID of the module on this server: by ID, then by `module`.
     *
     * @param array|null $module ['id' => ..., 'module' => ...]
     * @param string $permissionKey for the warning
     * @param array $stats
     * @return string|null
     */
    private static function resolveModuleID(?array $module, string $permissionKey, array &$stats): ?string
    {
        if (empty($module)) return NULL;

        $id = AppModule::whereKey($module['id'] ?? NULL)->value('id')
            ?? (!empty($module['module']) ? AppModule::where('module', $module['module'])->value('id') : NULL);

        if ($id === NULL) $stats['warnings'][] = "Permission \"{$permissionKey}\": module \"" . ($module['module'] ?? $module['id'] ?? '?') . "\" doesn't exist on this server, saved without a module.";
        return $id;
    }

    /**
     * The ID of the route on this server: by ID, then by module + `route_name`.
     *
     * @param array|null $route ['id' => ..., 'route_name' => ..., 'module' => ...]
     * @param string $permissionKey for the warning
     * @param array $stats
     * @return string|null
     */
    private static function resolveRouteID(?array $route, string $permissionKey, array &$stats): ?string
    {
        if (empty($route)) return NULL;

        $id = AppModuleRoute::whereKey($route['id'] ?? NULL)->value('id');
        if ($id === NULL && !empty($route['route_name'])) {
            $moduleID = !empty($route['module']) ? AppModule::where('module', $route['module'])->value('id') : NULL;
            $id = AppModuleRoute::where('route_name', $route['route_name'])
                ->when($moduleID, fn ($q) => $q->where('module_id', $moduleID))
                ->value('id');
        }

        if ($id === NULL) $stats['warnings'][] = "Permission \"{$permissionKey}\": route \"" . ($route['route_name'] ?? $route['id'] ?? '?') . "\" doesn't exist on this server, saved without a guarded route.";
        return $id;
    }
}
